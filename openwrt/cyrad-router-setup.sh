#!/bin/sh
# CYRAD — ONE router script: WireGuard tunnel + ubus disconnect + DNS blocking.
#
# Fetched and run on an OpenWrt router with:
#   wget -q http://<VPS>:8000/cyrad-router-setup.sh -O /tmp/cyrad-router.sh
#   sh /tmp/cyrad-router.sh
#
# It deliberately does NOT touch WiFi / RADIUS / PPPoE / LAN addressing, so it
# will not drop the SSH session. There is no inbound port-forward: the router
# only makes outbound connections (WireGuard keepalive + HTTPS/HTTP API).
#
# Required env (the VPS installer writes a ready-to-run /root/cyrad-router-bootstrap.sh):
#   BACKEND_IP, RADIUS_SECRET, API_TOKEN,
#   SERVER_ENDPOINT, SERVER_WG_IP, ROUTER_WG_IP,
#   SERVER_PUBLIC_KEY, ROUTER_PRIVATE_KEY, CYRAD_VPS_SSH_PUBKEY
# Optional:
#   WG_PORT (51820), CYRAD_HTTP_PORT (8000), ORG_ID (0 = all rules),
#   BACKEND_URL, LAN_IFACE, OPENWRT_LAN_IP, UPSTREAM_DNS
set -u

BACKEND_IP="${BACKEND_IP:-${SERVER_ENDPOINT:-}}"
SERVER_ENDPOINT="${SERVER_ENDPOINT:-$BACKEND_IP}"
WG_PORT="${WG_PORT:-51820}"
SERVER_WG_IP="${SERVER_WG_IP:-10.9.0.1}"
ROUTER_WG_IP="${ROUTER_WG_IP:-10.9.0.2}"
CYRAD_HTTP_PORT="${CYRAD_HTTP_PORT:-8000}"
RADIUS_SECRET="${RADIUS_SECRET:-}"
API_TOKEN="${API_TOKEN:-}"
ORG_ID="${ORG_ID:-0}"
BACKEND_URL="${BACKEND_URL:-http://$BACKEND_IP:8080}"
CYRAD_BOOTSTRAP_URL="${CYRAD_BOOTSTRAP_URL:-http://$SERVER_ENDPOINT:$CYRAD_HTTP_PORT}"
SERVER_PUBLIC_KEY="${SERVER_PUBLIC_KEY:-}"
ROUTER_PRIVATE_KEY="${ROUTER_PRIVATE_KEY:-}"
CYRAD_VPS_SSH_PUBKEY="${CYRAD_VPS_SSH_PUBKEY:-}"
UPSTREAM_DNS="${UPSTREAM_DNS:-8.8.8.8}"

for v in BACKEND_IP SERVER_PUBLIC_KEY ROUTER_PRIVATE_KEY API_TOKEN; do
  eval val=\$$v
  [ -n "$val" ] || { echo "[cyrad] ERROR: $v is required" >&2; exit 1; }
done

LAN_IFACE=$(uci -q get network.lan.device 2>/dev/null || uci -q get network.lan.ifname 2>/dev/null || echo br-lan)
OPENWRT_LAN_IP="${OPENWRT_LAN_IP:-192.168.2.1}"
OPENWRT_LAN_IP=$(uci -q get network.lan.ipaddr 2>/dev/null || echo "$OPENWRT_LAN_IP")
echo "==> [1/4] WireGuard tunnel (LAN=$LAN_IFACE, router=$ROUTER_WG_IP -> VPS=$SERVER_WG_IP)"

# ---- wireguard-tools (opkg first, HTTP package server fallback) ------------
if ! command -v wg >/dev/null 2>&1; then
  opkg update >/dev/null 2>&1 || true
  opkg install wireguard-tools kmod-wireguard >/dev/null 2>&1 || true
fi
if ! command -v wg >/dev/null 2>&1; then
  echo "    opkg unavailable; fetching packages from $CYRAD_BOOTSTRAP_URL"
  for f in wireguard-tools kmod-wireguard kmod-crypto-lib-chacha20poly1305 \
           kmod-crypto-lib-curve25519 kmod-crypto-kpp kmod-crypto-lib-chacha20 \
           kmod-crypto-lib-poly1305 kmod-udptunnel4 kmod-udptunnel6; do
    [ -s "/tmp/$f.ipk" ] || wget -q "$CYRAD_BOOTSTRAP_URL/$f.ipk" -O "/tmp/$f.ipk" || echo "    failed: $f"
  done
  opkg install --nodeps /tmp/wireguard-tools.ipk /tmp/kmod-wireguard.ipk \
    /tmp/kmod-crypto-lib-chacha20poly1305.ipk /tmp/kmod-crypto-lib-curve25519.ipk \
    /tmp/kmod-crypto-kpp.ipk /tmp/kmod-crypto-lib-chacha20.ipk \
    /tmp/kmod-crypto-lib-poly1305.ipk /tmp/kmod-udptunnel4.ipk \
    /tmp/kmod-udptunnel6.ipk 2>&1 | tail -8
fi
command -v wg >/dev/null 2>&1 || { echo "[cyrad] ERROR: wg binary missing" >&2; exit 1; }

cat > /usr/bin/cyrad-wg-up <<EOS
#!/bin/sh
# Generated by CYRAD cyrad-router-setup.sh — safe to run on every boot.
sleep 10
ip link del wg0 2>/dev/null || true
ip link add dev wg0 type wireguard
echo '$ROUTER_PRIVATE_KEY' > /tmp/cyrad-wg-private.key
chmod 600 /tmp/cyrad-wg-private.key
wg set wg0 private-key /tmp/cyrad-wg-private.key \\
  peer '$SERVER_PUBLIC_KEY' endpoint '$SERVER_ENDPOINT:$WG_PORT' \\
  allowed-ips '$SERVER_WG_IP/32' persistent-keepalive 25
ip address add '$ROUTER_WG_IP/32' dev wg0
ip link set wg0 up
ip route add '$SERVER_WG_IP/32' dev wg0 2>/dev/null || true
EOS
chmod 755 /usr/bin/cyrad-wg-up
grep -q cyrad-wg-up /etc/rc.local || \
  sed -i 's|^exit 0|/usr/bin/cyrad-wg-up \&\nexit 0|' /etc/rc.local
ip link del wg0 2>/dev/null || true
/usr/bin/cyrad-wg-up
sleep 3
ping -c 2 -W 2 "$SERVER_WG_IP" >/dev/null 2>&1 && echo "    tunnel OK" || echo "    WARNING: tunnel ping failed (check keys/endpoint)"

# ---- firewall: accept DAE on wg0 (fw4/nftables) ----------------------------
OLD_DAE_RULE=$(uci show firewall 2>/dev/null | sed -n "s/^firewall\.\([^.]*\)\.name='cyrad-dae-wg'.*/\1/p" | head -1)
[ -n "$OLD_DAE_RULE" ] && uci -q delete "firewall.$OLD_DAE_RULE"
uci -q delete firewall.cyrad_dae_wg
uci add firewall rule >/dev/null
uci set firewall.@rule[-1].name='cyrad-dae-wg'
uci set firewall.@rule[-1].src='*'
uci set firewall.@rule[-1].device='wg0'
uci set firewall.@rule[-1].proto='udp'
uci set firewall.@rule[-1].dest_port='3799'
uci set firewall.@rule[-1].target='ACCEPT'
LAN_ZONE=$(uci show firewall 2>/dev/null | sed -n "s/^firewall\.\([^.]*\)\.name='lan'.*/\1/p" | head -1)
if [ -n "$LAN_ZONE" ]; then
  uci set "firewall.$LAN_ZONE.input=ACCEPT"
  uci -q get "firewall.$LAN_ZONE.network" | grep -qw wg0 || uci add_list "firewall.$LAN_ZONE.network=wg0"
fi

echo "==> [2/4] ubus disconnect helper + VPS SSH key"
cat > /usr/bin/cyrad-kick <<'KICK'
#!/bin/sh
# Deauthenticate client MACs on every hostapd interface (no DAE reply needed).
for mac in "$@"; do
  m=$(printf '%s' "$mac" | tr 'A-F' 'a-f' | tr '-' ':')
  [ ${#m} -eq 17 ] || continue
  for h in $(ubus list 2>/dev/null | grep '^hostapd.wlan'); do
    ubus call "$h" del_client "{\"addr\":\"$m\",\"deauth\":true,\"ban_time\":0}" >/dev/null 2>&1
  done
done
exit 0
KICK
chmod 755 /usr/bin/cyrad-kick
if [ -n "$CYRAD_VPS_SSH_PUBKEY" ]; then
  mkdir -p /etc/dropbear
  touch /etc/dropbear/authorized_keys
  chmod 600 /etc/dropbear/authorized_keys
  grep -qF "$CYRAD_VPS_SSH_PUBKEY" /etc/dropbear/authorized_keys || \
    echo "$CYRAD_VPS_SSH_PUBKEY" >> /etc/dropbear/authorized_keys
  echo "    VPS key installed"
else
  echo "    WARNING: no VPS SSH public key supplied"
fi

# Point hostapd's DAE client at the tunnel source (no wifi reload — applied on
# the next natural WiFi restart; the ubus fallback works regardless).
IFC=$(uci show wireless 2>/dev/null | sed -n 's/^wireless\.\([^.]*\)\.auth_server=.*/\1/p' | head -1)
[ -z "$IFC" ] && IFC=$(uci show wireless 2>/dev/null | sed -n 's/^wireless\.\([^.]*\)\.dae_port=.*/\1/p' | head -1)
if [ -n "$IFC" ]; then
  uci set "wireless.$IFC.dae_port=3799"
  uci set "wireless.$IFC.dae_client=$SERVER_WG_IP"
  uci set "wireless.$IFC.dae_secret=$RADIUS_SECRET"
  uci commit wireless
fi

echo "==> [3/4] DNS blocklist (dnsmasq + API sync)"
cat > /etc/cyrad.conf <<EOF
BACKEND_URL="$BACKEND_URL"
BACKEND_IP="$BACKEND_IP"
ORG_ID="$ORG_ID"
API_TOKEN="$API_TOKEN"
UPSTREAM_DNS="$UPSTREAM_DNS"
LAN_IFACE="$LAN_IFACE"
OPENWRT_LAN_IP="$OPENWRT_LAN_IP"
EOF
chmod 600 /etc/cyrad.conf
mkdir -p /etc/dnsmasq.d
uci set dhcp.@dnsmasq[0].confdir='/etc/dnsmasq.d'
uci set dhcp.@dnsmasq[0].logqueries='1'
uci commit dhcp

cat > /usr/bin/cyrad-sync-blocklist <<'SYNC'
#!/bin/sh
. /etc/cyrad.conf
URL="$BACKEND_URL/admin/api_dns_rules.php?org=$ORG_ID&token=$API_TOKEN"
TMP=/etc/dnsmasq.d/cyrad-block.conf.new
CUR=/etc/dnsmasq.d/cyrad-block.conf
: > "$TMP"
if command -v uclient-fetch >/dev/null 2>&1; then
  uclient-fetch -q -O - "$URL" 2>/dev/null >> "$TMP"
elif command -v curl >/dev/null 2>&1; then
  curl -fsS "$URL" 2>/dev/null >> "$TMP"
fi
sed -i 's/^[[:space:]]*//; s/[[:space:]]*$//; /^$/d; s#^[*.]*##; s#^#address=/#; s#$#/#' "$TMP"
# dnsmasq reads conf-dir files only at startup: SIGHUP is NOT enough for
# address= rules. Restart only when the blocklist actually changed, so the
# 5-minute cron does not drop DNS every time it runs.
if ! cmp -s "$TMP" "$CUR" 2>/dev/null; then
  mv -f "$TMP" "$CUR"
  /etc/init.d/dnsmasq restart >/dev/null 2>&1 || killall -HUP dnsmasq 2>/dev/null || true
  sleep 2
else
  rm -f "$TMP"
fi
SYNC
chmod 755 /usr/bin/cyrad-sync-blocklist
/usr/bin/cyrad-sync-blocklist
COUNT=$(wc -l < /etc/dnsmasq.d/cyrad-block.conf 2>/dev/null || echo 0)
echo "    block rules loaded: $COUNT"

grep -q cyrad-sync-blocklist /etc/crontabs/root 2>/dev/null || \
  echo "*/5 * * * * /usr/bin/cyrad-sync-blocklist >/dev/null 2>&1" >> /etc/crontabs/root
service cron enable >/dev/null 2>&1 || true
service cron start >/dev/null 2>&1 || true

# Force all LAN DNS through this router (safe fallback if fw4 rejects the file).
mkdir -p /etc/nftables.d
# fw4 include files are inserted INSIDE table inet fw4 — declare only a chain.
# Priority dstnat-1 makes this run before fw4's own destination-NAT chain.
cat > /etc/nftables.d/cyrad-force-dns.nft <<NFT
chain cyrad_force_dns {
  type nat hook prerouting priority dstnat - 1; policy accept;
  iifname "$LAN_IFACE" udp dport 53 ip saddr != $OPENWRT_LAN_IP redirect to :53
  iifname "$LAN_IFACE" tcp dport 53 ip saddr != $OPENWRT_LAN_IP redirect to :53
}
NFT
if command -v fw4 >/dev/null 2>&1; then
  if ! fw4 check >/dev/null 2>&1 || ! fw4 reload >/dev/null 2>&1; then
    rm -f /etc/nftables.d/cyrad-force-dns.nft
    fw4 reload >/dev/null 2>&1 || true
    echo "    WARNING: forced-DNS nft rule rejected; removed (dnsmasq blocking still active)"
  else
    echo "    forced-LAN-DNS rule active"
  fi
fi

echo "==> [4/4] Applying"
killall -HUP dnsmasq 2>/dev/null || service dnsmasq restart >/dev/null 2>&1 || true
/etc/init.d/firewall reload >/dev/null 2>&1 || true

echo
echo "==> DONE. No WiFi restart was performed; SSH/WiFi clients stay connected."
echo "    Tunnel:      $(ip -4 addr show wg0 2>/dev/null | grep -oE '10\.[0-9.]+' | head -1) -> $SERVER_WG_IP"
echo "    Disconnect:  /usr/bin/cyrad-kick <MAC> via ubus (VPS calls it over WireGuard)"
echo "    DNS block:   /etc/dnsmasq.d/cyrad-block.conf ($COUNT rules), refresh every 5 min"
echo "    Verify:      nslookup <blocked-domain> $OPENWRT_LAN_IP"
