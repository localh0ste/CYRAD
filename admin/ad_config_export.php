<?php
/**
 * ad_config_export.php — print the panel's domain-controller settings as shell
 * environment lines, so freeradius/setup-ad.sh picks up whatever was typed in
 * Add User -> Active Directory without the values being copied by hand.
 *
 * Usage (root/CLI only):
 *   php admin/ad_config_export.php                      # to stdout, bind secret masked
 *   php admin/ad_config_export.php --env-file PATH      # real values, chmod 600
 *
 * Nothing is printed when AD is not configured, and the exit status is 1, so the
 * caller can fall back to its own defaults.
 */
if (PHP_SAPI !== 'cli' && PHP_SAPI !== 'phpdbg') {
    http_response_code(403);
    exit('Forbidden');
}

// config.php sits at the web root (../config.php from admin/) in a real install
// and at the repo root when running from a checkout.
$cfg = null;
foreach ([__DIR__ . '/../config.php', __DIR__ . '/config.php'] as $candidate) {
    if (is_file($candidate)) { $cfg = $candidate; break; }
}
if ($cfg === null) {
    fwrite(STDERR, "ad_config_export: config.php not found — cannot read DB credentials.\n");
    exit(2);
}
require_once $cfg;
// mysqli throws on failure (PHP 8.1+ default), so guard it: an unreachable
// database must leave the caller free to fall back, not die.
try {
    require_once __DIR__ . '/config/db.php';
} catch (Throwable $e) {
    fwrite(STDERR, "ad_config_export: database unavailable: {$e->getMessage()}\n");
    exit(2);
}
require_once __DIR__ . '/lib/ad_config.php';

$envFile = null;
for ($i = 1; $i < $argc; $i++) {
    if ($argv[$i] === '--env-file' && isset($argv[$i + 1])) {
        $envFile = $argv[++$i];
    } elseif (strpos($argv[$i], '--env-file=') === 0) {
        $envFile = substr($argv[$i], 11);
    }
}

if ($conn->connect_error) {
    fwrite(STDERR, "ad_config_export: database connection failed: {$conn->connect_error}\n");
    exit(2);
}

$c = ad_config_load($conn);
$conn->close();

if (!ad_config_ready($c)) {
    fwrite(STDERR, "ad_config_export: no domain controller configured in the panel.\n");
    exit(1);
}

// DC host: the typed IP wins over the host name, exactly like the LDAP URI.
$lines = [
    'CYRAD_AD_DOMAIN'    => ad_config_domain($c) !== '' ? ad_config_domain($c) : ad_config_const('CYRAD_AD_DOMAIN'),
    'CYRAD_AD_HOST'      => ad_config_host($c),
    'CYRAD_AD_BASE_DN'   => (string)$c['base_dn'],
    'CYRAD_AD_BIND_DN'   => (string)$c['bind_dn'],
    'CYRAD_AD_BIND_PASS' => (string)$c['bind_pass'],
    'CYRAD_AD_TLS'       => (int)$c['use_tls'] ? '1' : '0',
    'CYRAD_AD_PORT'      => (string)(int)$c['dc_port'],
    'CYRAD_AD_GROUP_DN'  => (string)$c['group_dn'],
];

if ($envFile !== null) {
    $body = "# Generated by admin/ad_config_export.php from the panel's ad_config row.\n";
    foreach ($lines as $k => $v) {
        if ($v === '' && $k !== 'CYRAD_AD_BIND_PASS') continue;
        $body .= $k . '=' . escapeshellarg((string)$v) . "\n";
    }
    if (@file_put_contents($envFile, $body) === false) {
        fwrite(STDERR, "ad_config_export: cannot write $envFile\n");
        exit(2);
    }
    @chmod($envFile, 0600);
    exit(0);
}

// stdout: mask the secret, it lands in terminals, scrollback and CI logs.
foreach ($lines as $k => $v) {
    if ($k === 'CYRAD_AD_BIND_PASS') {
        $v = $v !== '' ? '***' : '';
    }
    if ($v === '' && $k !== 'CYRAD_AD_BIND_PASS') continue;
    echo $k . '=' . $v . "\n";
}
exit(0);
