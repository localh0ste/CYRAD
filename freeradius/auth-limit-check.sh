#!/usr/bin/env bash
# ============================================================================
# CYRAD — FreeRADIUS auth-time limit + MAC-blacklist check.
#
# Patches the SQL module's authorize_check_query so EVERY authentication is
# evaluated against the live data cap and the MAC blacklist:
#
#   * over cap  -> an `Auth-Type := Reject` check item is returned and the
#     request is rejected even between cron runs;
#   * blacklisted MAC (Calling-Station-Id) -> same;
#   * when an admin raises the limit (or resets usage), the sum falls below the
#     limit again and the user rejoins immediately — no cron wait.
#
# Idempotent (marker CYRAD_AUTH_POLICY), backs up queries.conf, and validates
# with `freeradius -XC` when available. Called by setup-cyrad.sh on every
# install/update; safe to run alone:
#
#   sudo bash freeradius/auth-limit-check.sh
# ============================================================================
set -euo pipefail

FRC="${CYRAD_FRC:-/etc/freeradius/3.0}"
Q="$FRC/mods-config/sql/main/mysql/queries.conf"

if [ ! -f "$Q" ]; then
  echo "[auth-limit-check] $Q not found — is FreeRADIUS installed?" >&2
  exit 1
fi

BAK="$Q.cyrad-bak"
[ -f "$BAK" ] || cp -f "$Q" "$BAK"

python3 - "$Q" <<'PYEOF'
import re, sys

path = sys.argv[1]
text = open(path, encoding='utf-8').read()

block = '''# CYRAD_AUTH_POLICY: reject at authorize time when the rolling data cap is
# reached or the client MAC is blacklisted. Generated by
# freeradius/auth-limit-check.sh — edit that script, not this block.
authorize_check_query = "\\
\tSELECT id, username, attribute, value, op FROM ( \\
\t\tSELECT id, username, attribute, value, op, 0 AS zorder \\
\t\tFROM ${authcheck_table} \\
\t\tWHERE username = '%{SQL-User-Name}' \\
\t\tUNION ALL \\
\t\tSELECT 0, '%{SQL-User-Name}', 'Auth-Type', 'Reject', ':=', 1 \\
\t\tFROM data_limits d \\
\t\tWHERE d.username = '%{SQL-User-Name}' \\
\t\t  AND d.internet_limit > 0 \\
\t\t  AND LOWER(d.internet_type) <> 'unlimited' \\
\t\t  AND COALESCE((SELECT SUM(a.acctinputoctets + a.acctoutputoctets) FROM radacct a \\
\t\t                WHERE a.username = d.username \\
\t\t                  AND a.acctstarttime >= COALESCE(d.usage_reset_ts, NOW())), 0) >= d.internet_limit \\
\t\tUNION ALL \\
\t\tSELECT 0, '%{SQL-User-Name}', 'Auth-Type', 'Reject', ':=', 2 \\
\t\tFROM mac_blacklist b \\
\t\tWHERE b.mac <> '' AND UPPER(b.mac) = UPPER('%{Calling-Station-Id}') \\
\t\t  AND (b.expires_at IS NULL OR b.expires_at > NOW()) \\
\t) t ORDER BY zorder, id"
'''

marker = 'CYRAD_AUTH_POLICY'
if marker in text:
    text = re.sub(r'# CYRAD_AUTH_POLICY.*?ORDER BY zorder, id"\n', block, text, flags=re.S, count=1)
else:
    pat = re.compile(r'authorize_check_query\s*=\s*"\\\n(?:.*?\n)*?.*?ORDER BY id"', re.M)
    text, n = pat.subn(block.rstrip('\n'), text, count=1)
    if n != 1:
        sys.exit('[auth-limit-check] could not locate authorize_check_query in queries.conf')

open(path, 'w', encoding='utf-8').write(text)
print('[auth-limit-check] authorize_check_query patched (cap + MAC blacklist)')
PYEOF

if command -v freeradius >/dev/null 2>&1; then
  if freeradius -XC >/dev/null 2>&1; then
    echo "[auth-limit-check] freeradius -XC: configuration valid"
  else
    echo "[auth-limit-check] FreeRADIUS validation FAILED — restoring backup" >&2
    cp -f "$BAK" "$Q"
    freeradius -XC >&2 || true
    exit 1
  fi
fi
