#!/usr/bin/env bash
# CYRAD — set up the WireGuard SERVER on the VPS (idempotent).
#
# Generates the keypairs if absent, writes /etc/wireguard/wg0.conf, opens the
# UDP port, enables wg-quick, prepares the router bootstrap HTTP service, and
# writes a ready-to-run /root/cyrad-router-bootstrap.sh for the OpenWrt router.
# Safe to re-run: existing keys are preserved.
#
# Usage:
#   SERVER_ENDPOINT=<vps-ip> RADIUS_SECRET=<secret> API_TOKEN=<token> \
#     bash wireguard/server/setup-wireguard-server.sh
set -euo pipefail

SERVER_ENDPOINT="${SERVER_ENDPOINT:-$(curl -fsS --max-time 8 https://api.ipify.org 2>/dev/null || echo '')}"
WG_PORT="${WG_PORT:-51820}"
SERVER_WG_IP="${SERVER_WG_IP:-10.9.0.1}"
ROUTER_WG_IP="${ROUTER_WG_IP:-10.9.0.2}"
CYRAD_HTTP_PORT="${CYRAD_HTTP_PORT:-8000}"
ORG_ID="${ORG_ID:-0}"
WG_DIR="${WG_DIR:-/etc/wireguard}"
ENV_OUT="${ENV_OUT:-/root/cyrad-wireguard-router.env}"
PKG_DIR="${WG_PKG_DIR:-/root/cyrad-wireguard-packages}"
BOOTSTRAP_OUT="${BOOTSTRAP_OUT:-/root/cyrad-router-bootstrap.sh}"
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

[ -n "$SERVER_ENDPOINT" ] || { echo "ERROR: set SERVER_ENDPOINT=<vps-public-ip>"; exit 1; }
[ "$(id -u)" -eq 0 ] || { echo "ERROR: run as root"; exit 1; }

export DEBIAN_FRONTEND=noninteractive
if ! command -v wg >/dev/null 2>&1; then
  apt-get update -qq
  apt-get install -y -qq wireguard python3 >/dev/null
else
  command -v python3 >/dev/null 2>&1 || apt-get install -y -qq python3 >/dev/null
fi

umask 077
mkdir -p "$WG_DIR"

if [ -s "$WG_DIR/server_private.key" ]; then
  SERVER_PRIV=$(cat "$WG_DIR/server_private.key")
else
  SERVER_PRIV=$(wg genkey); printf '%s\n' "$SERVER_PRIV" > "$WG_DIR/server_private.key"
fi
SERVER_PUB=$(printf '%s\n' "$SERVER_PRIV" | wg pubkey)
printf '%s\n' "$SERVER_PUB" > "$WG_DIR/server_public.key"

if [ -n "${ROUTER_PRIVATE_KEY:-}" ]; then
  ROUTER_PRIV="$ROUTER_PRIVATE_KEY"
elif [ -s "$WG_DIR/router_private.key" ]; then
  ROUTER_PRIV=$(cat "$WG_DIR/router_private.key")
else
  ROUTER_PRIV=$(wg genkey)
fi
printf '%s\n' "$ROUTER_PRIV" > "$WG_DIR/router_private.key"
if [ -n "${ROUTER_PUBLIC_KEY:-}" ]; then
  ROUTER_PUB="$ROUTER_PUBLIC_KEY"
else
  ROUTER_PUB=$(printf '%s\n' "$ROUTER_PRIV" | wg pubkey)
fi
printf '%s\n' "$ROUTER_PUB" > "$WG_DIR/router_public.key"

cat > "$WG_DIR/wg0.conf" <<EOF
[Interface]
PrivateKey = $SERVER_PRIV
Address = $SERVER_WG_IP/32
ListenPort = $WG_PORT
SaveConfig = false

[Peer]
PublicKey = $ROUTER_PUB
AllowedIPs = $ROUTER_WG_IP/32
EOF
chmod 600 "$WG_DIR/wg0.conf"

ufw allow "${WG_PORT}/udp" >/dev/null 2>&1 || true
systemctl daemon-reload
systemctl enable "wg-quick@wg0" >/dev/null 2>&1 || true
systemctl restart "wg-quick@wg0" || wg-quick up wg0 || true

# ---- passwordless SSH key used by the VPS-to-router ubus kick helper --------
SSH_KEY="/root/.ssh/cyrad_router_ed25519"
mkdir -p /root/.ssh
[ -s "$SSH_KEY" ] || ssh-keygen -q -t ed25519 -N '' -f "$SSH_KEY"
VPS_SSH_PUB=$(cat "$SSH_KEY.pub")

cat > /usr/local/bin/cyrad_router_kick <<EOF
#!/bin/sh
# VPS helper: deauthenticate a MAC on the router over WireGuard (no password).
exec /usr/bin/ssh -i "$SSH_KEY" -o StrictHostKeyChecking=no \\
    -o UserKnownHostsFile=/dev/null -o ConnectTimeout=5 -o BatchMode=yes \\
    root@"$ROUTER_WG_IP" /usr/bin/cyrad-kick "\$@"
EOF
chmod 755 /usr/local/bin/cyrad_router_kick

# ---- bootstrap HTTP service (scripts + .ipk packages by IP) ----------------
CYRAD_HTTP_PORT="$CYRAD_HTTP_PORT" WG_PKG_DIR="$PKG_DIR" \
  bash "$REPO/wireguard/server/bootstrap-http-server.sh" --prepare >/dev/null

PY_BIN=$(command -v python3 || echo /usr/bin/python3)
cat > /etc/systemd/system/cyrad-wg-bootstrap.service <<EOF
[Unit]
Description=CYRAD WireGuard router bootstrap files (HTTP :$CYRAD_HTTP_PORT)
After=network.target

[Service]
Type=simple
ExecStart=$PY_BIN -m http.server $CYRAD_HTTP_PORT --bind 0.0.0.0 --directory $PKG_DIR
Restart=always
RestartSec=3
User=root

[Install]
WantedBy=multi-user.target
EOF
ufw allow "${CYRAD_HTTP_PORT}/tcp" >/dev/null 2>&1 || true
systemctl daemon-reload
systemctl enable cyrad-wg-bootstrap >/dev/null 2>&1 || true
systemctl restart cyrad-wg-bootstrap || true

# ---- env file for manual/setup use ----------------------------------------
cat > "$ENV_OUT" <<EOF
# Generated by setup-wireguard-server.sh — source this, keep it chmod 600.
SERVER_ENDPOINT='$SERVER_ENDPOINT'
WG_PORT='$WG_PORT'
SERVER_WG_IP='$SERVER_WG_IP'
ROUTER_WG_IP='$ROUTER_WG_IP'
SERVER_PUBLIC_KEY='$SERVER_PUB'
ROUTER_PRIVATE_KEY='$ROUTER_PRIV'
RADIUS_SECRET='${RADIUS_SECRET:-}'
API_TOKEN='${API_TOKEN:-}'
ORG_ID='${ORG_ID:-0}'
CYRAD_HTTP_PORT='$CYRAD_HTTP_PORT'
CYRAD_VPS_SSH_PUBKEY='$VPS_SSH_PUB'
ROUTER_SSH_HOST='$ROUTER_WG_IP'
CYRAD_KICK_BIN='/usr/local/bin/cyrad_router_kick'
EOF
chmod 600 "$ENV_OUT"

# ---- one-line router bootstrap (root-only; contains the router private key) -
shquote() { printf "%s" "$1" | sed "s/'/'\\\\''/g; s/^/'/; s/$/'/"; }
Q_ENDPOINT=$(shquote "$SERVER_ENDPOINT")
Q_WGPORT=$(shquote "$WG_PORT")
Q_SIP=$(shquote "$SERVER_WG_IP")
Q_RIP=$(shquote "$ROUTER_WG_IP")
Q_SPUB=$(shquote "$SERVER_PUB")
Q_RPRIV=$(shquote "$ROUTER_PRIV")
Q_SEC=$(shquote "${RADIUS_SECRET:-}")
Q_API=$(shquote "${API_TOKEN:-}")
Q_HTTP=$(shquote "$CYRAD_HTTP_PORT")
Q_PUBKEY=$(shquote "$VPS_SSH_PUB")
ORG_QUOTED=$(shquote "$ORG_ID")

cat > "$BOOTSTRAP_OUT" <<EOF
#!/bin/sh
# Generated by CYRAD on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file root-only.
# Copy the whole line below into the OpenWrt router root shell.
set -e
export SERVER_ENDPOINT=$Q_ENDPOINT
export WG_PORT=$Q_WGPORT
export SERVER_WG_IP=$Q_SIP
export ROUTER_WG_IP=$Q_RIP
export SERVER_PUBLIC_KEY=$Q_SPUB
export ROUTER_PRIVATE_KEY=$Q_RPRIV
export RADIUS_SECRET=$Q_SEC
export API_TOKEN=$Q_API
export CYRAD_HTTP_PORT=$Q_HTTP
export CYRAD_VPS_SSH_PUBKEY=$Q_PUBKEY
export ORG_ID=$ORG_QUOTED
export BACKEND_IP=\$SERVER_ENDPOINT
export CYRAD_BOOTSTRAP_URL=http://\$SERVER_ENDPOINT:\$CYRAD_HTTP_PORT
wget -q "\$CYRAD_BOOTSTRAP_URL/cyrad-router-setup.sh" -O /tmp/cyrad-router-setup.sh
sh /tmp/cyrad-router-setup.sh
EOF
chmod 700 "$BOOTSTRAP_OUT"

echo "==> WireGuard server is up:"
wg show wg0 | sed -n '1,12p'
echo "==> Router env:          $ENV_OUT"
echo "==> Router bootstrap:    $BOOTSTRAP_OUT  (copy this file to the router and run it)"
echo "==> Bootstrap HTTP:      http://$SERVER_ENDPOINT:$CYRAD_HTTP_PORT/ (service cyrad-wg-bootstrap)"
